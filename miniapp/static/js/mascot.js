// static/js/mascot.js — маскот: мордочка и реплика зависят от настроения.
import { esc } from './utils.js';

const FACES = {
  idle: ['(｡•̀ᴗ-)✧', '(๑˃ᴗ˂)ﻭ', '(≧◡≦)'],
  work: ['(ง •̀_•́)ง', '( ˘▽˘)っ♨', '٩(•̤̀ᵕ•̤́๑)'],
  blush: ['(⁄ ⁄>⁄ ▽ ⁄<⁄ ⁄)', '(*/ω＼*)', '(〃ω〃)'],
  err: ['(╥﹏╥)', '(；ω；)'],
};

const LINES = {
  idle: [
    'Ну что, принёс мне что-нибудь погорячее? Кидай ссылку, не стесняйся~',
    'Покажи свой стрим, а я найду в нём самое интересное!',
    'Давай-давай, не томи! Ссылка или файл — что у тебя?',
  ],
  scan: [
    'Так-так, что тут у нас... Только не подглядывай, я сосредоточена!',
    'Ой-ой, сколько всего! Ищу самые жаркие моменты~',
    'Тсс! Я слушаю дорожку. Не отвлекай меня, ладно?',
  ],
  up: [
    'Ммм, файл грузится... Не закрывай приложение, а то всё сорвётся!',
    'Держи крепче, не отпускай! Загрузка идёт~',
  ],
  err: [
    'Ай! Что-то пошло не так... Это не я, честно!',
    'Упс, сломалось. Давай попробуем ещё разок?',
  ],
  profile: ['Тут твои тарифы и всякие скучные взрослые штуки (¬‿¬)'],
};

const SFX = { scan: 'ドキドキ', up: 'ぐいっ!', err: 'ガーン' };

export class Mascot {
  constructor() {
    this._said = {};   // выбранные реплики: пока экран не сменился, текст не прыгает при перерисовке
  }

  reset() {
    this._said = {};
  }

  sfx(kind) {
    return SFX[kind];
  }

  _pick(key, variants) {
    return this._said[key] || (this._said[key] = variants[Math.floor(Math.random() * variants.length)]);
  }

  /** Блок «мордочка + реплика». mood — набор мордочек, key — набор реплик. */
  hero(mood, key) {
    return `<div class="hero"><div class="face">${esc(this._pick('f' + mood + key, FACES[mood]))}</div>` +
           `<div class="bubble">${esc(this._pick('l' + key, LINES[key]))}</div></div>`;
  }
}
